// Коллизии. Методы решения и какой метод используется в го?

// Разрешение коллизий в хеш-функциях
// http://genius.pstu.ru/file.php/1/pupils_works_2017/MuhinaAlisa.pdf
func task9_1() int {
	// Функция каждый раз возвращает случайный хеш.
	// Это обеспечивает равномерное распредление по бакетам при вставке элементов в мапу.
	// Только при чтении мы уже не сможем обратиться в тот бакет, в который положили наше значение, потому что хэш-функция вернет другое значение.
	// Здесь происходит нарушение детерменированности и предскауемости хэш-функции.
	return randomInt(100)
}

func randomInt(max int) int {
	return rand.IntN(max)
}

func task9_2() int {
	// Функция hash2 всегда возвращает единицу.
	// Это значит, что в мапе у нас будет 10 элементов, которые будут иметь одинаковые хеши, будет возникать большое количество коллизий.
	// Все элементы мапы будут хранится в одном бакете.
	// С такой функцией вычисления мапы мы получаем массив.
	// Сложность получения элементов в худшем случае будет O(n).
	// Функция детерминированна, что является плюсом.
	return 1
}
