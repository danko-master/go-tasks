// type bmap struct {
//     tophash [bucketCnt]uint8 // bucketCnt равен 8. Хранит старшие 8 битов хэша ключа
//     // -- далее в памяти идут 8 ключей типа K
//     // -- затем 8 значений типа V
//     // -- затем указатель на следующий переполненный бакет (overflow *bmap)
