// Как устроено хранение внутри бакета.

// tophash:
// Массив из 8 чисел uint8.
// Когда вы ищете ключ, Go сначала считает хэш и берет его верхний байт (tophash).
// Он сравнивает его с массивом tophash бакета.
// Если байт не совпал, ключ точно отсутствует — это позволяет не читать сами ключи из памяти (ускоряет поиск).

// Плотная упаковка данных:
// Сначала в памяти лежат 8 ключей подряд (k0, k1, ..., k7), а затем 8 значений подряд (v0, v1, ..., v7).
// Это сделано специально для того, чтобы избежать пустого пространства (padding),
// которое возникает из-за выравнивания памяти (alignment), если чередовать ключ-значение-ключ-значение.

// Overflow-бакеты:
// Если в одном бакете заполнилось все 8 ячеек, а хэши продолжают попадать сюда же (коллизия),
// Go создает дополнительный бакет (overflow bucket) и связывает текущий бакет указателем с ним.

// Переполнение
// Если все аллоцированые бакеты в среднем заполнены на 6,5, то начинается эвакуация данных.
// 6,5  - это "идеальное" сочетание между переполнением и необходимым выделением памяти.

